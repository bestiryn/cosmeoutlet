-- ห้ามนำ service_role key หรือรหัสผ่านฐานข้อมูล (postgresql://...) มาใส่ในโค้ดหน้าเว็บ
-- โดยเด็ดขาด เพราะจะเท่ากับเปิดสิทธิ์ระดับสูงสุดของฐานข้อมูลให้ใครก็ได้ที่เปิดดูโค้ดหน้าเว็บ
