-- ---------- 1) ตารางสินค้า ----------
create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  name        text not null unique,
  category    text not null check (category in ('perfume', 'skincare', 'cosmetics')),
  price       numeric(10, 2) not null default 0,
  description text not null default '',
  image_url   text not null default '',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

comment on table public.products is 'สินค้าที่แสดงในหน้า products.html ของ Cosme Outlet';

-- เก็บเวลาแก้ไขล่าสุดอัตโนมัติ
create or replace function public.set_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists trg_products_updated_at on public.products;
create trigger trg_products_updated_at
  before update on public.products
  for each row execute function public.set_updated_at();

-- ---------- 2) Row Level Security ----------
alter table public.products enable row level security;

drop policy if exists "Public read access" on public.products;
create policy "Public read access" on public.products
  for select using (true);

drop policy if exists "Public insert access" on public.products;
create policy "Public insert access" on public.products
  for insert with check (true);

drop policy if exists "Public update access" on public.products;
create policy "Public update access" on public.products
  for update using (true) with check (true);

drop policy if exists "Public delete access" on public.products;
create policy "Public delete access" on public.products
  for delete using (true);

-- ---------- 3) Storage bucket สำหรับรูปสินค้าที่อัปโหลดจากหน้า admin ----------
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

drop policy if exists "Public read product images" on storage.objects;
create policy "Public read product images" on storage.objects
  for select using (bucket_id = 'product-images');

drop policy if exists "Public upload product images" on storage.objects;
create policy "Public upload product images" on storage.objects
  for insert with check (bucket_id = 'product-images');

drop policy if exists "Public update product images" on storage.objects;
create policy "Public update product images" on storage.objects
  for update using (bucket_id = 'product-images') with check (bucket_id = 'product-images');

drop policy if exists "Public delete product images" on storage.objects;
create policy "Public delete product images" on storage.objects
  for delete using (bucket_id = 'product-images');

